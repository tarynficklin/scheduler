-- The tables and indexes of master_seed.sql, created only when they're missing: nothing is dropped and
-- no rows are added. `bun run db:migrate` runs this before each deployed start; master_seed.sql is
-- the one that re-creates everything with the dev account. Keep the two in step.

--base table (local accounts; the Auth0 auth_id / auth_profile columns are gone)
CREATE TABLE IF NOT EXISTS users (
	user_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_name     VARCHAR(100) NOT NULL,
	user_email    VARCHAR(100),
	password_hash TEXT NOT NULL
);

-- Usernames and emails are unique, case-insensitively (login accepts either).
CREATE UNIQUE INDEX IF NOT EXISTS users_user_name_key ON users (lower(user_name));

CREATE UNIQUE INDEX IF NOT EXISTS users_user_email_key ON users (lower(user_email));

--trips are a child of users
-- (BY DEFAULT identity: POST /api/trips may still pass the trip_id that GET /api/trips reserved)
CREATE TABLE IF NOT EXISTS trips (
	trip_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id         INTEGER NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
	trip_location   TEXT DEFAULT '',
	trip_start_date VARCHAR(10) DEFAULT '',
	trip_end_date   VARCHAR(10) DEFAULT '',
	trip_budget     DOUBLE PRECISION DEFAULT 0,
	trip_background TEXT DEFAULT '',
	trip_bg_color   TEXT DEFAULT ''
);

CREATE INDEX IF NOT EXISTS trips_user_id_idx ON trips (user_id);

--packing lists are a child of trips
CREATE TABLE IF NOT EXISTS packing_lists (
	packing_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	trip_id         INTEGER NOT NULL REFERENCES trips (trip_id) ON DELETE CASCADE,
	packing_title   VARCHAR(100) DEFAULT '',
	packing_checked BOOLEAN DEFAULT false
);

CREATE INDEX IF NOT EXISTS packing_lists_trip_id_idx ON packing_lists (trip_id);

--schedules (one per trip day) are a child of trips
CREATE TABLE IF NOT EXISTS schedules (
	schedule_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	trip_id       INTEGER NOT NULL REFERENCES trips (trip_id) ON DELETE CASCADE,
	schedule_date VARCHAR(50) DEFAULT ''
);

CREATE INDEX IF NOT EXISTS schedules_trip_id_idx ON schedules (trip_id);

--schedule items are a child of schedules
CREATE TABLE IF NOT EXISTS schedule_items (
	item_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	schedule_id  INTEGER NOT NULL REFERENCES schedules (schedule_id) ON DELETE CASCADE,
	item_title   VARCHAR(100) DEFAULT '',
	item_price   DOUBLE PRECISION DEFAULT 0,
	item_time    VARCHAR(10) DEFAULT 'morning',
	item_checked BOOLEAN DEFAULT false
);

CREATE INDEX IF NOT EXISTS schedule_items_schedule_id_idx ON schedule_items (schedule_id);
